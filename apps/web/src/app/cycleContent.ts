/** What to do with today's training, from the phase and how the body feels. `light` offers the lighter workout. */
export function trainingAdvice(phase: CyclePhase | null, pms: boolean, feeling: Feeling | null): { text: string; light: boolean } {
  if (feeling === 'bad') return { text: 'Сегодня лучше облегчённая тренировка (вес ×0,9, подходов на один меньше, запас 3–4 повторения) или прогулка и растяжка. Полноценную проведёшь в другой день.', light: true };
  if (feeling === null) return { text: 'Отметь самочувствие: по нему подберём нагрузку на сегодня.', light: false };
  if (phase === 'ovulatory') return { text: 'Тренируйся по плану, разминайся подольше и следи за техникой в приседе, выпадах и прыжках.', light: false };
  if (phase === 'menstrual' && feeling === 'ok') return { text: 'Тренируйся по плану. Если по ходу станет тяжело, облегчи подходы: сегодня не день рекордов.', light: false };
  if ((phase === 'luteal' && pms) && feeling === 'ok') return { text: 'Тренируйся по плану, но без борьбы за максимум: упор на технику, отдыхай подольше.', light: false };
  if (phase === 'follicular' && feeling === 'good') return { text: 'Хорошие дни для прогрессии: если есть запас, смело добавляй вес по плану.', light: false };
  return { text: 'Тренируйся по плану.', light: false };
}

