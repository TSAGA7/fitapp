export function GoalExplainBody({ initial }: { initial: GoalType }) {
  const { snapshot: s } = useData();
  const [goal, setGoal] = useState<GoalType>(initial);
  const t = TEXTS[goal];
  const p = s.profile;
  const weight = s.weight.currentKg;
  const calc =
    p && weight !== null
      ? computeTargets({ sex: p.sex, ageYears: ageYears(p.birthDate, s.today), heightCm: p.heightCm, weightKg: weight, jobActivity: p.jobActivity, trainingsPerWeek: trainingDays(p.trainingSchedule).length, goal })
      : null;
  const adj = GOAL_ADJUSTMENT[goal];
  return (
    <div className="stack">
      <div className="chips" role="group" aria-label="Цель">
        {GOALS.map((g) => <Chip key={g} pressed={goal === g} onClick={() => setGoal(g)}>{GOAL_LABELS[g].title}</Chip>)}
      </div>
      <section className="stack">
        <h3 className="t-h3">{GOAL_LABELS[goal].title}: в чём идея</h3>
        <p className="t-body">{t.why}</p>
      </section>
      <section className="stack">
        <h3 className="t-h3">Почему такие калории и БЖУ</h3>
        <p className="t-body">{t.calories}</p>
        <p className="t-body">{t.protein}</p>
        {calc && (
          <Card flat>
            <div className="stack t-small">
              <div>Твой расчёт для этой цели (по текущему весу {fmt(weight ?? 0)} кг):</div>
              <div>Базовый обмен: {calc.bmr} ккал</div>
              <div>Расход с учётом работы и {trainingDays(p!.trainingSchedule).length} тренировок в неделю: {calc.tdee} ккал</div>
              <div>Поправка цели: {adj === 0 ? 'нет' : `${adj > 0 ? '+' : '−'}${Math.abs(Math.round(adj * 100))}%`}</div>
              <div><b>Норма: {calc.targets.kcal} ккал · белок {calc.targets.proteinG} г ({PROTEIN_PER_KG[goal]} г/кг) · жиры {calc.targets.fatG} г · углеводы {calc.targets.carbG} г</b></div>
            </div>
          </Card>
        )}
      </section>
      <section className="stack">
        <h3 className="t-h3">Как устроено питание в целом</h3>
        <ul className="t-body">{COMMON.map((x) => <li key={x}>{x}</li>)}</ul>
      </section>
      <section className="stack">
        <h3 className="t-h3">Почему такие тренировки и нагрузки</h3>
        <p className="t-body">{t.training}</p>
        <ul className="t-body">{TRAINING_COMMON.map((x) => <li key={x}>{x}</li>)}</ul>
      </section>
      <p className="t-small">{t.watch}</p>
      <p className="t-small">Это расчёты по общепринятым формулам, не медицинские рекомендации. При хронических заболеваниях и беременности планируй питание и нагрузки с врачом.</p>
    </div>
  );
}

export function GoalExplainSheet({ open, goal, onClose }: { open: boolean; goal: GoalType; onClose: () => void }) {
  return (
    <Sheet open={open} title="Почему такая программа" onClose={onClose}>
      {open && <GoalExplainBody initial={goal} />}
    </Sheet>
  );
}
